//! voXY developer tasks: `cargo xtask <task>`.
//!
//! - `licenses`: regenerate `docs/third-party-licenses.md` from `cargo metadata`.
//! - `licenses --check`: fail if that file is out of date (used by CI).
//! - `am-inspect FILE... [--out REPORT.md]`: what each Alight Motion sample
//!   contains (container, entries, lossless round trip) plus an inventory of
//!   every element, attribute and value shape, as Markdown for
//!   `docs/am-format.md`.
//! - `am-diff A B`: structural differences between two exports of the same
//!   project (differential analysis). Zip packages are compared entry by
//!   entry.

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::{Path, PathBuf};
use std::process::Command;

use anyhow::{Context, Result, bail};
use serde_json::Value;

fn main() -> Result<()> {
    let args: Vec<String> = std::env::args().skip(1).collect();
    match args.first().map(String::as_str) {
        Some("licenses") => licenses(args.get(1).is_some_and(|a| a == "--check")),
        Some("am-inspect") => am_inspect(&args[1..]),
        Some("am-diff") if args.len() == 3 => am_diff(Path::new(&args[1]), Path::new(&args[2])),
        _ => {
            eprintln!(
                "usage:\n  cargo xtask licenses [--check]\n  cargo xtask am-inspect FILE... [--out REPORT.md]\n  cargo xtask am-diff A B"
            );
            std::process::exit(2);
        }
    }
}

fn workspace_root() -> PathBuf {
    // Prefer the run-time value `cargo run` sets: the compile-time one goes
    // stale if the binary was built from another checkout sharing `target/`.
    let manifest_dir = std::env::var_os("CARGO_MANIFEST_DIR")
        .map_or_else(|| PathBuf::from(env!("CARGO_MANIFEST_DIR")), PathBuf::from);
    Path::new(&manifest_dir)
        .parent()
        .expect("xtask lives in the workspace")
        .to_path_buf()
}

fn licenses(check: bool) -> Result<()> {
    let root = workspace_root();
    let out = Command::new(env!("CARGO"))
        .current_dir(&root)
        .args(["metadata", "--format-version", "1", "--locked"])
        .output()
        .context("running cargo metadata")?;
    if !out.status.success() {
        bail!(
            "cargo metadata failed: {}",
            String::from_utf8_lossy(&out.stderr)
        );
    }
    let meta: Value = serde_json::from_slice(&out.stdout)?;
    let members: Vec<&str> = meta["workspace_members"]
        .as_array()
        .context("workspace_members")?
        .iter()
        .filter_map(Value::as_str)
        .collect();

    // name -> (versions, license, repository)
    let mut crates: BTreeMap<String, (Vec<String>, String, String)> = BTreeMap::new();
    let mut by_license: BTreeMap<String, usize> = BTreeMap::new();
    for p in meta["packages"].as_array().context("packages")? {
        let id = p["id"].as_str().unwrap_or_default();
        if members.contains(&id) {
            continue;
        }
        let name = p["name"].as_str().unwrap_or_default().to_owned();
        let version = p["version"].as_str().unwrap_or_default().to_owned();
        let license = p["license"]
            .as_str()
            .map(normalize)
            .or_else(|| p["license_file"].as_str().map(|f| format!("see {f}")))
            .unwrap_or_else(|| "UNSPECIFIED".to_owned());
        let repo = p["repository"].as_str().unwrap_or_default().to_owned();
        let entry = crates
            .entry(name)
            .or_insert_with(|| (Vec::new(), license.clone(), repo));
        if !entry.0.contains(&version) {
            entry.0.push(version);
            entry.0.sort();
        }
    }
    for (_, license, _) in crates.values() {
        *by_license.entry(license.clone()).or_default() += 1;
    }

    let mut md = String::new();
    md.push_str("# Third-party Rust dependencies\n\n");
    md.push_str(
        "Generated by `cargo xtask licenses` from `Cargo.lock`; do not edit by hand.\n\
         CI fails if this file is stale. The policy that every license must satisfy is in\n\
         [`LICENSING.md`](../LICENSING.md) and is enforced by `cargo deny` (`deny.toml`).\n\n\
         The list covers every target platform, so it includes crates that are only\n\
         compiled on Windows, macOS or Linux.\n\n",
    );
    let _ = writeln!(md, "{} crates.\n", crates.len());
    md.push_str("## By license\n\n| License | Crates |\n|---|---|\n");
    for (license, n) in &by_license {
        let _ = writeln!(md, "| `{license}` | {n} |");
    }
    md.push_str("\n## Crates\n\n| Crate | Version(s) | License |\n|---|---|---|\n");
    for (name, (versions, license, repo)) in &crates {
        let crate_cell = if repo.is_empty() {
            format!("`{name}`")
        } else {
            format!("[`{name}`]({repo})")
        };
        let _ = writeln!(
            md,
            "| {crate_cell} | {} | `{license}` |",
            versions.join(", ")
        );
    }

    let path = root.join("docs/third-party-licenses.md");
    if check {
        let current = std::fs::read_to_string(&path).unwrap_or_default();
        if current != md {
            bail!(
                "{} is out of date; run `cargo xtask licenses`",
                path.display()
            );
        }
        println!("{} is up to date", path.display());
    } else {
        std::fs::write(&path, md)?;
        println!("wrote {} ({} crates)", path.display(), crates.len());
    }
    Ok(())
}

/// Normalizes legacy `/`-separated license lists to SPDX `OR`.
fn normalize(license: &str) -> String {
    license.replace(" / ", " OR ").replace('/', " OR ")
}

fn file_label(path: &Path) -> String {
    path.file_name().map_or_else(
        || path.display().to_string(),
        |n| n.to_string_lossy().into_owned(),
    )
}

fn am_inspect(args: &[String]) -> Result<()> {
    use voxy_am_compat::inspect::inspect;
    use voxy_am_compat::inventory::Inventory;

    let mut files = Vec::new();
    let mut out = None;
    let mut it = args.iter();
    while let Some(a) = it.next() {
        if a == "--out" {
            out = Some(PathBuf::from(it.next().context("--out needs a path")?));
        } else {
            files.push(PathBuf::from(a));
        }
    }
    if files.is_empty() {
        bail!("no sample files given");
    }
    let mut md = String::from(
        "# Alight Motion sample inspection\n\nGenerated by `cargo xtask am-inspect`.\n\n",
    );
    let mut inventory = Inventory::default();
    for path in &files {
        if path.extension().is_some_and(|e| e == "md") {
            continue;
        }
        let bytes = std::fs::read(path).with_context(|| format!("reading {}", path.display()))?;
        match inspect(&file_label(path), bytes) {
            Ok(report) => {
                md.push_str(&report.to_markdown());
                report.add_to(&mut inventory);
            }
            Err(e) => {
                let _ = writeln!(
                    md,
                    "## Sample `{}`\n\n**Could not open:** {e}\n",
                    file_label(path)
                );
            }
        }
    }
    md.push_str("# Inventory\n\n");
    md.push_str(&inventory.to_markdown());
    match out {
        Some(p) => {
            std::fs::write(&p, &md)?;
            println!("wrote {}", p.display());
        }
        None => print!("{md}"),
    }
    Ok(())
}

fn am_diff(a: &Path, b: &Path) -> Result<()> {
    use voxy_am_compat::diff::diff;
    use voxy_am_compat::inspect::inspect;

    let ra = inspect(&file_label(a), std::fs::read(a)?)?;
    let rb = inspect(&file_label(b), std::fs::read(b)?)?;
    let names: std::collections::BTreeSet<&String> =
        ra.documents.keys().chain(rb.documents.keys()).collect();
    let mut total = 0;
    for name in names {
        let label = if name.is_empty() {
            "(file)".to_owned()
        } else {
            name.clone()
        };
        match (ra.documents.get(name), rb.documents.get(name)) {
            (Some(da), Some(db)) => {
                let changes = diff(da, db);
                if !changes.is_empty() {
                    println!("== {label}");
                    for c in &changes {
                        println!("{c}");
                    }
                    total += changes.len();
                }
            }
            (Some(_), None) => {
                println!("== {label}: only in {}", a.display());
                total += 1;
            }
            _ => {
                println!("== {label}: only in {}", b.display());
                total += 1;
            }
        }
    }
    // Archive entries: report additions, removals and size changes of
    // non-XML entries (only meaningful between two zip packages).
    if !(ra.is_zip && rb.is_zip) {
        println!("{total} structural change(s)");
        return Ok(());
    }
    let entries = |r: &voxy_am_compat::inspect::SampleReport| -> BTreeMap<String, u64> {
        r.entries.iter().map(|e| (e.name.clone(), e.size)).collect()
    };
    let (ea, eb) = (entries(&ra), entries(&rb));
    for (name, size) in &ea {
        match eb.get(name) {
            None => println!("- entry {name}"),
            Some(s) if s != size && !ra.documents.contains_key(name) => {
                println!("~ entry {name}: {size} -> {s} bytes");
            }
            _ => {}
        }
    }
    for name in eb.keys().filter(|n| !ea.contains_key(*n)) {
        println!("+ entry {name}");
    }
    println!("{total} structural change(s)");
    Ok(())
}
